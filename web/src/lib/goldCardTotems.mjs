/** 四芒星（E106 世界牌同源笔法） */
const st4 = (x, y, r, fill = C, op = 0.85) =>
  `<path d="M${x} ${y - r} L${(x + r * 0.32).toFixed(1)} ${(y - r * 0.32).toFixed(1)} L${x + r} ${y} L${(x + r * 0.32).toFixed(1)} ${(y + r * 0.32).toFixed(1)} L${x} ${y + r} L${(x - r * 0.32).toFixed(1)} ${(y + r * 0.32).toFixed(1)} L${x - r} ${y} L${(x - r * 0.32).toFixed(1)} ${(y - r * 0.32).toFixed(1)} Z" fill="${fill}" opacity="${op}"/>`;

/** 斜置四芒星（45° —— 八芒星叠加用） */
